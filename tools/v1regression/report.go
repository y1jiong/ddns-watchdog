package main

import (
	"fmt"
	"strings"
)

// renderReport writes a Markdown summary of a harness run.
func renderReport(ref1, ref2 string, targets []*Target, results []Result) string {
	var b strings.Builder

	b.WriteString("# v1 → v2 regression report\n\n")
	fmt.Fprintf(&b, "Baseline `%s` (version %s) vs `%s` (version %s).\n\n",
		ref1, targets[0].Version, ref2, targets[1].Version)
	b.WriteString("Generated by `go run ./tools/v1regression`. Each scenario drives both revisions " +
		"through the same local fake services and compares exit codes, output, written files, " +
		"outbound requests and HTTP responses.\n\n")

	b.WriteString("## Summary\n\n")
	b.WriteString("| # | scenario | result | note |\n|---|---|---|---|\n")
	for i, r := range results {
		status, note := "identical", ""
		switch {
		case r.Err != nil:
			status, note = "harness error", r.Err.Error()
		case len(r.Unexplained) > 0:
			status = "**REGRESSION**"
			note = truncate(oneLine(r.Unexplained[0].V1)+" ≠ "+oneLine(r.Unexplained[0].V2), 120)
		case len(r.Differences) > 0:
			status, note = fmt.Sprintf("%d intended difference(s)", len(r.Differences)), truncate(r.Differences[0].Why, 120)
		}
		fmt.Fprintf(&b, "| %d | `%s` | %s | %s |\n", i+1, r.Scenario, status, note)
	}
	b.WriteString("\n")

	b.WriteString("## Deliberate differences (checked)\n\n")
	a := false
	for _, r := range results {
		if len(r.Differences) == 0 {
			continue
		}
		a = true
		fmt.Fprintf(&b, "### `%s`\n\n%s\n\n", r.Scenario, r.Scenario.Doc)
		for _, d := range r.Differences {
			fmt.Fprintf(&b, "- **%s** — %s\n", d.Field, d.Why)
			fmt.Fprintf(&b, "  - v1: `%s`\n", oneLine(d.V1))
			fmt.Fprintf(&b, "  - v2: `%s`\n", oneLine(d.V2))
		}
		b.WriteString("\n")
	}
	if !a {
		b.WriteString("_none_\n\n")
	}

	b.WriteString("## Unexplained differences\n\n")
	broken := false
	for _, r := range results {
		if len(r.Unexplained) == 0 {
			continue
		}
		broken = true
		fmt.Fprintf(&b, "### `%s`\n\n", r.Scenario)
		for _, d := range r.Unexplained {
			fmt.Fprintf(&b, "- **%s**\n  - v1: `%s`\n  - v2: `%s`\n", d.Field, oneLine(d.V1), oneLine(d.V2))
		}
		b.WriteString("\n")
	}
	if !broken {
		b.WriteString("_none_\n\n")
	}

	b.WriteString("## Scenarios\n\n")
	b.WriteString("| scenario | what it pins |\n|---|---|\n")
	for _, r := range results {
		fmt.Fprintf(&b, "| `%s` | %s |\n", r.Scenario, r.Scenario.Doc)
	}

	return b.String()
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}
